import { describe, it, expect, vi } from 'vitest'
import { render, screen, within } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { HelmetProvider } from 'react-helmet-async'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { AI_DISCLOSURE_COPY } from '../components/ai/aiDisclosureCopy'
import MethodologyPage from './MethodologyPage'
import StewardshipPage from './StewardshipPage'
import ThankYouPage from './ThankYouPage'

vi.mock('../components/SubscribeProvider', () => ({
  useSubscribe: () => ({ openSubscribe: vi.fn() }),
}))

vi.mock('../hooks/useSources', () => ({
  useSources: () => ({
    data: {
      byRegion: { 'North America': ['Reuters', 'AP'] },
      byIssue: { 'Planet & Climate': ['Mongabay', 'Grist'] },
      totalCount: 82,
    },
    isLoading: false,
  }),
}))

function renderPage(component: React.ReactElement) {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  return render(
    <QueryClientProvider client={queryClient}>
      <HelmetProvider>
        <MemoryRouter>{component}</MemoryRouter>
      </HelmetProvider>
    </QueryClientProvider>,
  )
}

describe('MethodologyPage', () => {
  it('renders dynamic source count from useSources hook', () => {
    renderPage(<MethodologyPage />)
    expect(screen.getByText(/82 curated news sources/)).toBeInTheDocument()
  })

  it('says what AI generates and selects, that no editor reviews it, and where to report a wrong label', () => {
    renderPage(<MethodologyPage />)
    const item = screen.getByText("We don't do original reporting.").closest('li')!
    expect(item.textContent!.replace(/\s+/g, ' ')).toBe(
      "We don't do original reporting. Every story links to the original source article. " +
        'Headlines, summaries, blurbs, relevance analyses, and social posts are generated by AI. ' +
        'AI also rates each story, selects the stories we publish, and sets the emotion tag behind the dial. ' +
        'Quotes are selected by AI and translated into English where needed. ' +
        "No editor reviews anything before it's published. " +
        "Spotted AI content without a label, or a label that's wrong? Tell us on the feedback page.",
    )
    expect(screen.getByRole('link', { name: 'feedback page' })).toHaveAttribute('href', '/feedback')
    expect(screen.queryByText(/clearly labeled/)).toBeNull()
  })

  it('quotes the researched-story label as the story page shows it', () => {
    renderPage(<MethodologyPage />)
    const heading = screen.getByRole('heading', { name: 'Researched Stories' })
    const { lead, tail } = AI_DISCLOSURE_COPY.researchedStoryLabel
    expect(heading.nextElementSibling?.nextElementSibling?.textContent).toContain(`carry the label "${lead} AI${tail}" and list`)
  })

  it('names only what research found as a reason not to publish, and no time limit among the single-source cases (owner decisions 2026-11-12)', () => {
    renderPage(<MethodologyPage />)
    const checks = (screen.getByRole('heading', { name: 'Researched Stories' }).nextElementSibling?.nextElementSibling?.textContent ?? '').replace(/\s+/g, ' ')
    expect(checks).toContain("If the research shows that the story is old news or is contradicted by other reports, we don't publish it.")
    expect(checks).not.toMatch(/matters less/)
    // A story still owed research at the daily publish usually goes out researched a day later
    expect(checks).toContain('or the research fails or would exceed our monthly research budget, we publish the single-source version instead.')
  })
})

describe('StewardshipPage', () => {
  it('renders heading and dynamic source count', () => {
    renderPage(<StewardshipPage />)
    expect(screen.getByRole('heading', { level: 1, name: /long-term home/i })).toBeInTheDocument()
    expect(screen.getByText(/with 82 curated sources across/)).toBeInTheDocument()
  })

  it('says what a steward inherits in its own section, between the tech stack and who we are looking for', () => {
    renderPage(<StewardshipPage />)
    const heading = screen.getByRole('heading', { level: 2, name: 'What a Steward Inherits' })
    const techStack = screen.getByRole('button', { name: /tech stack/i })
    const nextSection = screen.getByRole('heading', { level: 2, name: "Who We're Looking For" })
    expect(techStack.compareDocumentPosition(heading)).toBe(Node.DOCUMENT_POSITION_FOLLOWING)
    expect(heading.compareDocumentPosition(nextSection)).toBe(Node.DOCUMENT_POSITION_FOLLOWING)

    const section = heading.closest('div')!
    expect(within(section).getByRole('heading', { level: 3, name: 'What moves' })).toBeInTheDocument()
    expect(within(section).getByRole('heading', { level: 3, name: 'Keeping it running' })).toBeInTheDocument()
    // The running cost is stated above, in the costs panel; this section only points back to it.
    expect(section.textContent).not.toContain('$')
    // The podcast feed answers with XML, so its address is plain text, not a link.
    expect(within(section).getByText(/actuallyrelevant\.news\/podcast\.xml/)).toBeInTheDocument()
    expect(within(section).queryAllByRole('link')).toHaveLength(0)
  })
})

describe('ThankYouPage', () => {
  it('renders heading and credit sections', () => {
    renderPage(<ThankYouPage />)
    expect(screen.getByRole('heading', { level: 1, name: /thank you/i })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: /frontend/i })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: /backend/i })).toBeInTheDocument()
  })
})
