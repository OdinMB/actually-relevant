/** Description of a field in AI_GENERATED_STORY_FIELDS: the "AI-generated." label, then the details. */
function aiField(details: string): string {
  return `${OPENAPI_AI_FIELD_PREFIX}${details}`
}

// --- Reusable schemas ---

const issueRefSchema = z
  .object({
    name: z.string().openapi({ example: 'Planet & Climate' }),
    slug: z.string().openapi({ example: 'planet-climate' }),
  })
  .openapi({ ref: 'IssueRef' })

const feedRefSchema = z
  .object({
    id: z.string().uuid(),
    title: z.string().openapi({ example: 'The Guardian Environment' }),
    displayTitle: z.string().nullable().openapi({ example: 'The Guardian' }),
    issue: issueRefSchema.nullable(),
  })
  .openapi({ ref: 'FeedRef' })

const aiGeneratedSchema = z
  .object({
    fields: z.array(z.enum(AI_GENERATED_STORY_FIELDS)).openapi({
      description: 'Names of the fields in this story object whose text was generated by an AI model. Only fields that carry a value are listed.',
      example: ['title', 'titleLabel', 'summary', 'relevanceReasons', 'antifactors'],
    }),
    model: z.string().openapi({
      description:
        'Id of the OpenAI model configured for story analysis when this response was served. ' +
        'Per-story model ids are not recorded, so stories analyzed before a model change were generated by an earlier model.',
      example: 'gpt-6-luna',
    }),
    digitalSourceType: z.literal(IPTC_TRAINED_ALGORITHMIC_MEDIA).openapi({
      description: 'IPTC Digital Source Type term for content created by a trained algorithmic model.',
    }),
  })
  .openapi({
    ref: 'AiGenerated',
    description:
      'Machine-readable marker of the AI-generated fields in this story. ' +
      'Unsigned metadata in the API response: it is not a watermark, and text copied out of the response does not carry it.',
  })

const publicStorySchema = z
  .object({
    id: z.string().uuid(),
    slug: z.string().nullable().openapi({ example: 'new-coral-reef-discovered-pacific' }),
    sourceUrl: z.string().url().openapi({ example: 'https://example.com/article' }),
    sourceTitle: z.string().openapi({
      description: 'Original headline of the source article (not AI-generated).',
      example: 'Major climate breakthrough announced',
    }),
    title: z
      .string()
      .nullable()
      .openapi({
        description: aiField('Headline written by an AI model.'),
        example: 'Scientists announce major climate breakthrough',
      }),
    titleLabel: z
      .string()
      .nullable()
      .openapi({ description: aiField('Short topic label written by an AI model.'), example: 'Climate' }),
    dateCrawled: z.string().datetime(),
    datePublished: z.string().datetime().nullable(),
    status: z.enum(['published']),
    relevancePre: z.number().int().min(0).max(10).nullable().openapi({
      description: 'Pre-assessment relevance rating assigned by an AI model.',
    }),
    relevance: z.number().int().min(0).max(10).nullable().openapi({
      description: 'Relevance rating assigned by an AI model.',
      example: 8,
    }),
    emotionTag: z.enum(['uplifting', 'frustrating', 'scary', 'calm']).nullable().openapi({
      description: 'Emotional tone assigned by an AI model.',
    }),
    summary: z
      .string()
      .nullable()
      .openapi({
        description: aiField('Summary written by an AI model.'),
        example: 'Researchers have developed a new carbon capture method...',
      }),
    quote: z
      .string()
      .nullable()
      .openapi({
        description: aiField(
          'Key quote selected from the source article by an AI model, which translates it to English when the source is in another language.',
        ),
      }),
    quoteAttribution: z
      .string()
      .nullable()
      .openapi({ description: aiField('Attribution of the quote, written by an AI model.') }),
    marketingBlurb: z
      .string()
      .nullable()
      .openapi({ description: aiField('Short teaser written by an AI model.') }),
    relevanceReasons: z
      .string()
      .nullable()
      .openapi({
        description: aiField('Reasons the story matters, written by an AI model as Markdown bullet points, one per line.'),
      }),
    relevanceSummary: z
      .string()
      .nullable()
      .openapi({ description: aiField('Short relevance summary written by an AI model.') }),
    antifactors: z
      .string()
      .nullable()
      .openapi({
        description: aiField('Caveats written by an AI model as Markdown bullet points, one per line.'),
      }),
    issue: issueRefSchema.nullable(),
    feed: feedRefSchema,
    aiGenerated: aiGeneratedSchema,
  })
  .openapi({ ref: 'PublicStory' })

const paginationMeta = {
  total: z.number().int().openapi({ example: 142 }),
  page: z.number().int().openapi({ example: 1 }),
  pageSize: z.number().int().openapi({ example: 25 }),
  totalPages: z.number().int().openapi({ example: 6 }),
}

const storyListResponseSchema = z
  .object({
    data: z.array(publicStorySchema),
    ...paginationMeta,
  })
  .openapi({ ref: 'StoryListResponse' })

const makeADifferenceSchema = z.object({
  label: z.string().openapi({ example: 'Donate to reforestation' }),
  url: z.string().url().openapi({ example: 'https://example.org/donate' }),
})

// eslint-disable-next-line @typescript-eslint/no-explicit-any -- recursive schema (children), which z.lazy needs annotated
const publicIssueSchema: z.ZodType<any> = z
  .object({
    id: z.string().uuid(),
    name: z.string().openapi({ example: 'Planet & Climate' }),
    slug: z.string().openapi({ example: 'planet-climate' }),
    description: z.string(),
    intro: z.string(),
    evaluationIntro: z.string(),
    evaluationCriteria: z.array(z.string()),
    makeADifference: z.array(makeADifferenceSchema),
    parentId: z.string().uuid().nullable(),
    sourceNames: z.array(z.string()),
    children: z.array(z.lazy(() => publicIssueSchema)).optional(),
  })
  .openapi({ ref: 'PublicIssue' })

const emotionBucketSchema = z.object({
  uplifting: z.array(publicStorySchema),
  calm: z.array(publicStorySchema),
  negative: z.array(publicStorySchema),
})

const homepageResponseSchema = z
  .object({
    issues: z.array(publicIssueSchema),
    storiesByIssue: z.record(z.string(), emotionBucketSchema),
  })
  .openapi({ ref: 'HomepageResponse' })

const podcastEpisodeSchema = z
  .object({
    id: z.string().uuid().openapi({ description: 'Stable episode id; also the feed item GUID.' }),
    title: z
      .string()
      .openapi({ description: aiField('Episode title written by an AI model (a person may have edited it).'), example: 'W41: Clean air and new vaccines' }),
    aiLine: z.string().openapi({
      description:
        'Disclosure line that starts the episode description in the feed. Says the episode was written and voiced by AI, and whether a person edited it.',
    }),
    summary: z.string().openapi({ description: aiField('Episode summary written by an AI model (a person may have edited it).') }),
    publishedAt: z.string().datetime(),
    durationSec: z.number().int().nullable(),
    audioUrl: z
      .string()
      .url()
      .openapi({
        description: aiField('MP3 of the episode: a dialogue written by an AI model and spoken by two synthetic AI voices.'),
        example: 'https://audio.actuallyrelevant.news/episodes/2026-W41-1a2b3c4d.mp3',
      }),
    audioBytes: z.number().int(),
    transcriptUrl: z
      .string()
      .url()
      .nullable()
      .openapi({ description: aiField('WebVTT transcript of the AI-written dialogue, with approximate timings.') }),
    stories: z.array(
      z.object({
        title: z.string().openapi({ description: aiField('Headline written by an AI model for the story page.') }),
        publisher: z.string(),
        sourceUrl: z.string().url(),
        slug: z.string().nullable(),
      }),
    ),
    aiGenerated: z
      .object({
        fields: z.array(z.enum(AI_GENERATED_PODCAST_FIELDS)),
        digitalSourceType: z.literal(IPTC_TRAINED_ALGORITHMIC_MEDIA),
      })
      .openapi({ description: 'Machine-readable marker of the AI-generated fields of this episode. Unsigned metadata, not a watermark.' }),
  })
  .openapi({ ref: 'PodcastEpisode' })

const podcastEpisodeDetailSchema = podcastEpisodeSchema
  .extend({
    transcript: z
      .array(
        z.object({
          story: z
            .object({
              title: z.string().openapi({ description: aiField('Headline written by an AI model for the story page.') }),
              publisher: z.string(),
              sourceUrl: z.string().url(),
              slug: z.string().nullable(),
            })
            .nullable()
            .openapi({ description: 'The story this part of the conversation is about; null for the opening, intro, outro and sign-off.' }),
          turns: z.array(
            z.object({
              speaker: z.enum(['Host A', 'Host B']).openapi({ description: 'One of the two generic AI hosts.' }),
              text: z.string(),
            }),
          ),
        }),
      )
      .openapi({
        description: aiField(
          'The episode as spoken, in order: the fixed opening and sign-off and the dialogue written by an AI model (a person may have edited it), ' +
            'one entry per part of the conversation, audio tags left out.',
        ),
      }),
    aiGenerated: z
      .object({
        fields: z.array(z.enum(AI_GENERATED_PODCAST_DETAIL_FIELDS)),
        digitalSourceType: z.literal(IPTC_TRAINED_ALGORITHMIC_MEDIA),
      })
      .openapi({ description: 'Machine-readable marker of the AI-generated fields of this episode. Unsigned metadata, not a watermark.' }),
  })
  .openapi({ ref: 'PodcastEpisodeDetail' })

const podcastResponseSchema = z
  .object({
    show: z.object({
      title: z.string().openapi({ example: 'Actually Relevant' }),
      description: z.string().openapi({ description: 'Standing show description, including that the show is written and voiced by AI.' }),
      feedUrl: z.string().url().openapi({ example: 'https://actuallyrelevant.news/podcast.xml' }),
      artworkUrl: z.string().url().openapi({ description: 'Square show artwork (3000 px JPEG), made from the brand logo, not AI-generated.' }),
      listenLinks: z.array(z.object({ name: z.string(), url: z.string().url() })),
    }),
    episodes: z.array(podcastEpisodeSchema),
  })
  .openapi({ ref: 'PodcastResponse' })

// Incremental-sync query parameters, documented from the same Zod schemas the routes validate with.
const minRelevanceQuery = minRelevanceParam.optional().openapi({
  description:
    'Only stories whose relevance rating is at least this value (1-10). ' +
    'Combine with publishedSince to fetch only high-signal stories since your last poll.',
  example: 7,
})

const storySyncQuerySchema = z.object({
  publishedSince: publishedSinceParam.optional().openapi({
    description:
      'Only stories published at or after this ISO 8601 date-time (inclusive, compared with `datePublished`). ' +
      'Pass the `datePublished` of the newest story you already have, or the time of your last poll.',
    example: '2026-10-01T00:00:00Z',
  }),
  publishedBefore: publishedBeforeParam.optional().openapi({
    description: 'Only stories published before this ISO 8601 date-time (exclusive). Must be later than publishedSince.',
    example: '2026-10-08T00:00:00Z',
  }),
  minRelevance: minRelevanceQuery,
})

const feedQueryDocSchema = z.object({ minRelevance: minRelevanceQuery })

const newsletterIssueSummarySchema = z
  .object({
    slug: z.string().openapi({ description: 'URL segment of the issue; never changes once assigned.', example: 'week-42-2026' }),
    title: z.string().openapi({ example: 'Week 42, 2026' }),
    publishedAt: z.string().datetime().openapi({ description: 'When the issue was first published.' }),
    storyCount: z.number().int(),
  })
  .openapi({ ref: 'NewsletterIssueSummary' })

const newsletterArchiveResponseSchema = z
  .object({
    data: z.array(newsletterIssueSummarySchema),
    total: z.number().int(),
    page: z.number().int(),
    pageSize: z.number().int(),
    totalPages: z.number().int(),
  })
  .openapi({ ref: 'NewsletterArchiveResponse' })

const newsletterIssueSchema = z
  .object({
    slug: z.string().openapi({ example: 'week-42-2026' }),
    title: z.string().openapi({ example: 'Week 42, 2026' }),
    publishedAt: z.string().datetime(),
    aiLabel: z.object({ lead: z.string(), text: z.string() }).openapi({
      description: 'The AI label shown at the top of the issue, in the email and on the web.',
    }),
    content: z.string().openapi({
      description: aiField(
        'The issue as Markdown: an intro written by an AI model, then one section per issue area with the AI-selected stories, ' +
          'each with its AI headline, publisher, links and an AI summary or a quote selected by AI.',
      ),
    }),
    stories: z
      .array(
        z.object({
          headline: z.string().openapi({ description: 'The heading the story has in `content`.' }),
          title: z.string().nullable(),
          titleLabel: z.string().nullable(),
          sourceTitle: z.string(),
          sourceUrl: z.string().url(),
          publisher: z.string(),
          slug: z.string().nullable().openapi({ description: 'Story page slug; null if the story is no longer published.' }),
        }),
      )
      .openapi({ description: aiField('The stories AI selected for the issue, with the headlines and title labels an AI model wrote.') }),
    aiGenerated: z
      .object({
        fields: z.array(z.enum(AI_GENERATED_NEWSLETTER_FIELDS)),
        digitalSourceType: z.literal(IPTC_TRAINED_ALGORITHMIC_MEDIA),
      })
      .openapi({ description: 'Machine-readable marker of the AI-generated fields of this issue. Unsigned metadata, not a watermark.' }),
  })
  .openapi({ ref: 'NewsletterIssue' })

const errorResponseSchema = z
  .object({
    error: z.string().openapi({ example: 'Not found' }),
  })
  .openapi({ ref: 'ErrorResponse' })

